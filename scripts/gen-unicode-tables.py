#!/usr/bin/env python3
"""Generate the Unicode tables the formatters need from Python's unicodedata.

Usage (inside `nix develop`):

    python3 scripts/gen-unicode-tables.py

Writes:
- src/output/width_table.rs: code point ranges whose
  `unicodedata.east_asian_width` is W, F, or A (`awscli/table.py`
  `get_text_length` counts them as 2 columns).
- src/pyfmt/printable_table.rs: code point ranges for which
  `str.isprintable()` is false (`repr(str)` escapes them).
"""

import os
import sys
import unicodedata

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def ranges(pred):
    out = []
    start = None
    for cp in range(0x110000):
        if pred(cp):
            if start is None:
                start = cp
        elif start is not None:
            out.append((start, cp - 1))
            start = None
    if start is not None:
        out.append((start, 0x10FFFF))
    return out


def write(path, doc, name, rs):
    lines = [
        f"//! {doc}",
        "//!",
        f"//! Generated by `scripts/gen-unicode-tables.py` from Python {sys.version.split()[0]}",
        f"//! (unicodedata {unicodedata.unidata_version}). Do not edit.",
        "",
        "#[rustfmt::skip]",
        f"pub(crate) static {name}: &[(u32, u32)] = &[",
    ]
    for a, b in rs:
        lines.append(f"    (0x{a:X}, 0x{b:X}),")
    lines.append("];")
    with open(os.path.join(ROOT, path), "w") as f:
        f.write("\n".join(lines) + "\n")


write(
    "src/output/width_table.rs",
    "Code points with East Asian Width W, F, or A.",
    "WIDE",
    ranges(lambda cp: unicodedata.east_asian_width(chr(cp)) in "WFA"),
)
write(
    "src/pyfmt/printable_table.rs",
    "Code points for which Python's `str.isprintable()` is false.",
    "NON_PRINTABLE",
    ranges(lambda cp: not chr(cp).isprintable()),
)
