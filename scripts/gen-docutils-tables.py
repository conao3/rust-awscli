#!/usr/bin/env python3
r"""Generate the character tables of the docutils port from Python's unicodedata.

Usage (inside `nix develop`):

    python3 scripts/gen-docutils-tables.py

Writes src/help/docutils/unicode_tables.rs: the `\w`, `\d` and `str.isspace()`
classes of Python's `re` and `str`, and `unicodedata.east_asian_width` W/F and
`unicodedata.combining` (`docutils.utils.column_width`).
"""

import os
import sys
import unicodedata

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def ranges(pred):
    out = []
    start = None
    for cp in range(0x110000):
        if pred(cp):
            if start is None:
                start = cp
        elif start is not None:
            out.append((start, cp - 1))
            start = None
    if start is not None:
        out.append((start, 0x10FFFF))
    return out


def emit(name, doc, rs):
    s = f"/// {doc}\npub(super) static {name}: &[(u32, u32)] = &[\n"
    for a, b in rs:
        s += f"    (0x{a:04X}, 0x{b:04X}),\n"
    return s + "];\n"


def main():
    out = (
        "//! Generated by `scripts/gen-docutils-tables.py`. Character tables from Python "
        + sys.version.split()[0]
        + " `unicodedata` (Unicode "
        + unicodedata.unidata_version
        + ").\n\n"
    )
    out += emit(
        "WORD",
        "Characters `\\w` matches in a `str` pattern (`str.isalnum()` or `_`).",
        ranges(lambda c: chr(c).isalnum() or c == 0x5F),
    )
    out += "\n" + emit(
        "DECIMAL",
        "Characters `\\d` matches in a `str` pattern (`str.isdecimal()`).",
        ranges(lambda c: chr(c).isdecimal()),
    )
    out += "\n" + emit(
        "SPACE",
        "Characters for which `str.isspace()` is true.",
        ranges(lambda c: chr(c).isspace()),
    )
    out += "\n" + emit(
        "WIDE",
        "Characters whose `unicodedata.east_asian_width` is W or F.",
        ranges(lambda c: unicodedata.east_asian_width(chr(c)) in "WF"),
    )
    out += "\n" + emit(
        "COMBINING",
        "Characters whose `unicodedata.combining` is nonzero.",
        ranges(lambda c: unicodedata.combining(chr(c)) != 0),
    )
    path = os.path.join(ROOT, "src", "help", "docutils", "unicode_tables.rs")
    with open(path, "w") as f:
        f.write(out)


if __name__ == "__main__":
    main()
