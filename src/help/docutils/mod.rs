use parser::{Flow, MsgArgs, P, Sm, St};
use statemachine::{StringList, string2lines};

/// The output of [`publish_man`].
#[derive(Debug, Clone, PartialEq, Eq)]
pub(crate) struct Published {
    /// The roff source (`publish_string`'s result).
    pub man: String,
    /// What docutils wrote to stderr (system messages at or above the
    /// report level).
    pub stderr: String,
}

/// The `SystemMessage` raised for a message at the halt level: the
/// message text and what docutils wrote to stderr before raising it.
#[derive(Debug, Clone, PartialEq, Eq)]
pub(crate) struct Halted {
    pub message: String,
    pub stderr: String,
}

/// The halted publish as the `String` error of a caller that only reports
/// the exception: the messages docutils wrote before raising go to stderr
/// first, as `Reporter.system_message` writes them before raising
/// `SystemMessage`.
impl From<Halted> for String {
    fn from(h: Halted) -> String {
        eprint!("{}", h.stderr);
        h.message
    }
}

/// `docutils.core.publish_string(rst, writer=manpage.Writer(),
/// settings_overrides={'line_length_limit': 50000})`.
pub(crate) fn publish_man(rst: &str) -> Result<Published, Halted> {
    let mut p = P::new();
    match run(&mut p, rst) {
        Ok(man) => Ok(Published {
            man,
            stderr: p.stderr,
        }),
        Err(Flow::Halt(message)) => Err(Halted {
            message,
            stderr: p.stderr,
        }),
        Err(other) => panic!("unexpected parser control flow {other:?}"),
    }
}

/// `Publisher.publish`: parse, transform, write.
fn run(p: &mut P, rst: &str) -> Result<String, Flow> {
    let input = rst.replace('\u{feff}', "");
    let lines = string2lines(&input, 8);
    if let Some(i) = lines.iter().position(|l| l.chars().count() > 50_000) {
        let e = p.error(
            &format!("Line {} exceeds the line-length-limit.", i + 1),
            MsgArgs::default(),
        )?;
        p.doc.append(0, e);
    } else {
        let list = StringList::new(lines);
        p.top = Some((list.clone(), -1));
        let mut sm = Sm::new(list, 0, 0, true);
        sm.is_top = true;
        p.run(&mut sm, St::Body)?;
    }
    p.apply_transforms()?;
    p.write_manpage()
}

#[cfg(test)]
mod tests {
    use super::manpage::MACRO_DEF;
    use super::publish_man;

    /// The expected output of docutils 0.19 for a document whose body
    /// (from `.TH` on) is `body`.
    fn expected(body: &str) -> String {
        format!(".\\\" Man page generated from reStructuredText.\n.\n{MACRO_DEF}{body}")
    }

    #[test]
    fn sections_inline_lists_literal_and_note() {
        let rst = "*****\ntitle\n*****\n\n=======\nSection\n=======\n\nSome *text* with ``code`` and a `link <http://example.com>`__.\n\n* a\n* b\n\n::\n\n  literal\n\n.. note::\n\n   noted\n";
        let out = publish_man(rst).unwrap();
        assert_eq!(
            out.man,
            expected(
                ".TH \"TITLE\"  \"\" \"\" \"\"\n.SH NAME\ntitle \\- Section\n.sp\nSome \\fItext\\fP with \\fBcode\\fP and a \\fI\\%link\\fP\\&.\n.INDENT 0.0\n.IP \\(bu 2\na\n.IP \\(bu 2\nb\n.UNINDENT\n.INDENT 0.0\n.INDENT 3.5\n.sp\n.nf\n.ft C\nliteral\n.ft P\n.fi\n.UNINDENT\n.UNINDENT\n.sp\n\\fBNOTE:\\fP\n.INDENT 0.0\n.INDENT 3.5\nnoted\n.UNINDENT\n.UNINDENT\n.\\\" Generated by docutils manpage writer.\n.\n"
            )
        );
        assert_eq!(out.stderr, "");
    }

    #[test]
    fn unknown_role_and_unclosed_emphasis() {
        let out = publish_man("text :doc:`x` and *open\n").unwrap();
        assert_eq!(
            out.stderr,
            "<string>:1: (ERROR/3) Unknown interpreted text role \"doc\".\n<string>:1: (WARNING/2) Inline emphasis start-string without end-string.\n"
        );
        assert_eq!(
            out.man,
            expected(
                ".TH \"\"  \"\" \"\" \"\"\n.SH NAME\n \\- \ntext \n.nf\n:doc:\\(gax\\(ga\n.fi\n and \n.nf\n*\n.fi\nopen\n.IP \"System Message: ERROR/3 (<string>:, line 1)\"\nUnknown interpreted text role \\(dqdoc\\(dq.\n.IP \"System Message: WARNING/2 (<string>:, line 1)\"\nInline emphasis start\\-string without end\\-string.\n.\\\" Generated by docutils manpage writer.\n.\n"
            )
        );
    }

    #[test]
    fn simple_table_and_unknown_target() {
        let rst = "=====  =====\ncol1   col2\n=====  =====\nx      y\n=====  =====\n\nSee unknown_ here.\n";
        let out = publish_man(rst).unwrap();
        assert_eq!(
            out.stderr,
            "<string>:7: (ERROR/3) Unknown target name: \"unknown\".\n"
        );
        assert_eq!(
            out.man,
            expected(
                ".TH \"\"  \"\" \"\" \"\"\n.SH NAME\n \\- \n.TS\ncenter;\n|l|l|.\n_\nT{\ncol1\nT}\tT{\ncol2\nT}\n_\nT{\nx\nT}\tT{\ny\nT}\n_\n.TE\n.sp\nSee \n.nf\nunknown_\n.fi\n here.\n.SH DOCUTILS SYSTEM MESSAGES\n.IP \"System Message: ERROR/3 (<string>:, line 7)\"\nUnknown target name: \\(dqunknown\\(dq.\n.\\\" Generated by docutils manpage writer.\n.\n"
            )
        );
    }

    #[test]
    fn severe_message_halts() {
        let err = publish_man("Title\n=====\n\nSub\n---\n\nBad\n~~~\n\nx\n\nOther\n-----\n\nWrong\n=====\ny\n\n- a\n\n  Title\n  =====\n").unwrap_err();
        assert!(err.message.contains("(SEVERE/4)"), "{err:?}");
        assert!(err.stderr.ends_with(&format!("{}\n", err.message)));
    }
}
