//! A port of the parts of docutils 0.19 the AWS CLI help renderer uses:
//! `docutils.core.publish_string(rst, writer=manpage.Writer(),
//! settings_overrides={'line_length_limit': 50000})` (the rst parser, the
//! standalone reader's transforms and the manpage writer), with the system
//! messages docutils writes to stderr.

