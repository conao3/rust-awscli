#!/usr/bin/env python3
"""Generate the tables `html.unescape` uses from Python's `html` module.

Usage (inside `nix develop`):

    python3 scripts/gen-html-entities.py

Writes src/help/entities.rs: `html.entities.html5` (sorted by name),
`html._invalid_charrefs`, and `html._invalid_codepoints`.
"""

import html
import html.entities
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def rust_str(s):
    out = '"'
    for c in s:
        if c in '"\\':
            out += '\\' + c
        elif 0x20 <= ord(c) < 0x7F:
            out += c
        else:
            out += '\\u{%x}' % ord(c)
    return out + '"'


def main():
    lines = [
        '//! Generated by `scripts/gen-html-entities.py`. Do not edit.',
        '',
        '/// `html.entities.html5`, sorted by name.',
        'pub(super) static HTML5: &[(&str, &str)] = &[',
    ]
    for name in sorted(html.entities.html5):
        lines.append(f'    ({rust_str(name)}, {rust_str(html.entities.html5[name])}),')
    lines.append('];')
    lines.append('')
    lines.append('/// `html._invalid_charrefs`, sorted by code point.')
    lines.append('pub(super) static INVALID_CHARREFS: &[(u32, &str)] = &[')
    for num in sorted(html._invalid_charrefs):
        lines.append(f'    ({num:#x}, {rust_str(html._invalid_charrefs[num])}),')
    lines.append('];')
    lines.append('')
    lines.append('/// `html._invalid_codepoints`, sorted.')
    lines.append('pub(super) static INVALID_CODEPOINTS: &[u32] = &[')
    for num in sorted(html._invalid_codepoints):
        lines.append(f'    {num:#x},')
    lines.append('];')
    with open(os.path.join(ROOT, 'src', 'help', 'entities.rs'), 'w') as f:
        f.write('\n'.join(lines) + '\n')


if __name__ == '__main__':
    main()
